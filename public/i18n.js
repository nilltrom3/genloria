// ---------- Detección y aplicación del idioma ----------
// La elección manual (localStorage) manda; si no hay, se detecta del teléfono.
function detectAppLang() {
  try {
    const saved = localStorage.getItem('genloria-lang');
    if (saved && STR[saved]) return saved;
  } catch (e) {}
  const nav = ((typeof navigator !== 'undefined' && navigator.language) || 'es')
    .toLowerCase().split('-')[0];
  return STR[nav] ? nav : 'es';
}
let appLang = detectAppLang();

// T('clave') / T('clave', { n: 3 }) — con parámetros {nombre}.
// Si la clave falta en el idioma activo, cae al español; si falta también
// ahí, devuelve la clave (comportamiento histórico de la app).
function T(k, params) {
  let s = (STR[appLang] && STR[appLang][k]) || STR.es[k] || k;
  if (params) {
    for (const p in params) s = s.split('{' + p + '}').join(String(params[p]));
  }
  return s;
}

// Locale Intl del idioma activo (fechas, meses, horas).
function appLocale() { return LOCALES[appLang] || 'es'; }

// Nombre del idioma activo en su propio idioma (para el botón selector).
function currentLangName() {
  const l = LANGS.find(x => x.code === appLang);
  return l ? l.name : 'Español';
}

// Traduce las etiquetas de la barra de navegación inferior (index.html).
function applyNavI18n() {
  if (typeof document === 'undefined') return;
  const map = {
    '#/feed': 'navHome', '#/tree': 'navTree', '#/new': 'navPost',
    '#/family': 'navFamily', '#/chat': 'navChat', '#/profile': 'navProfile'
  };
  document.querySelectorAll('#bottomnav button[data-nav]').forEach(b => {
    const k = map[b.dataset.nav];
    if (!k) return;
    const span = b.querySelector('span:not(.badge)');
    if (span) span.textContent = T(k);
    b.setAttribute('aria-label', T(k));
  });
}

// Cambia el idioma: guarda la elección manual y vuelve a dibujar la vista.
function setAppLang(code) {
  if (!STR[code]) code = 'es';
  appLang = code;
  try { localStorage.setItem('genloria-lang', code); } catch (e) {}
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', code);
  }
  applyNavI18n();
  // El enrutador de app.js escucha 'hashchange': un evento sintético lo
  // obliga a redibujar la vista actual ya en el idioma nuevo.
  if (typeof window !== 'undefined' && window.dispatchEvent) {
    try { window.dispatchEvent(new HashChangeEvent('hashchange')); } catch (e) {}
  }
}

// Al cargar: fijar <html lang> y traducir la navegación estática.
if (typeof document !== 'undefined') {
  document.documentElement.setAttribute('lang', appLang);
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyNavI18n);
  } else {
    applyNavI18n();
  }
}
